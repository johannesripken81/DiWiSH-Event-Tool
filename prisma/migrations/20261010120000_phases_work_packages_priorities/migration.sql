BEGIN;

ALTER TABLE "EventTask" ADD COLUMN "workPackage" TEXT;
ALTER TABLE "TaskTemplate" ADD COLUMN "workPackage" TEXT;

-- Preserve the mixed legacy category for manual classification.
UPDATE "EventTask" SET "workPackage" = CASE phase::text
  WHEN 'LOCATION_CATERING' THEN 'LOCATION_CATERING'
  WHEN 'SPEAKERS_PARTNERS' THEN 'LEGACY_SPEAKERS_PARTNERS'
  WHEN 'COMMUNICATION' THEN 'COMMUNICATION'
  WHEN 'PARTICIPANT_MANAGEMENT' THEN 'PARTICIPANT_MANAGEMENT'
  WHEN 'MATERIAL_PRESENTATION' THEN 'TECHNOLOGY_MATERIAL'
  WHEN 'TECHNOLOGY' THEN 'TECHNOLOGY_MATERIAL'
  ELSE NULL END;
UPDATE "TaskTemplate" SET "workPackage" = CASE phase::text
  WHEN 'LOCATION_CATERING' THEN 'LOCATION_CATERING'
  WHEN 'SPEAKERS_PARTNERS' THEN 'LEGACY_SPEAKERS_PARTNERS'
  WHEN 'COMMUNICATION' THEN 'COMMUNICATION'
  WHEN 'PARTICIPANT_MANAGEMENT' THEN 'PARTICIPANT_MANAGEMENT'
  WHEN 'MATERIAL_PRESENTATION' THEN 'TECHNOLOGY_MATERIAL'
  WHEN 'TECHNOLOGY' THEN 'TECHNOLOGY_MATERIAL'
  ELSE NULL END;

CREATE TYPE "EventPhase_new" AS ENUM ('CONCEPTION', 'PLANNING', 'EXECUTION', 'FOLLOW_UP');
ALTER TABLE "EventTask" ALTER COLUMN phase TYPE "EventPhase_new" USING
  (CASE phase::text WHEN 'CONCEPTION' THEN 'CONCEPTION' WHEN 'FOUR_EYES_REVIEW' THEN 'CONCEPTION'
    WHEN 'EVENT_DAY' THEN 'EXECUTION' WHEN 'FOLLOW_UP' THEN 'FOLLOW_UP' WHEN 'EVALUATION' THEN 'FOLLOW_UP'
    ELSE 'PLANNING' END)::"EventPhase_new";
ALTER TABLE "TaskTemplate" ALTER COLUMN phase TYPE "EventPhase_new" USING
  (CASE phase::text WHEN 'CONCEPTION' THEN 'CONCEPTION' WHEN 'FOUR_EYES_REVIEW' THEN 'CONCEPTION'
    WHEN 'EVENT_DAY' THEN 'EXECUTION' WHEN 'FOLLOW_UP' THEN 'FOLLOW_UP' WHEN 'EVALUATION' THEN 'FOLLOW_UP'
    ELSE 'PLANNING' END)::"EventPhase_new";
DROP TYPE "EventPhase";
ALTER TYPE "EventPhase_new" RENAME TO "EventPhase";

-- Keep the event-critical flag when converting the former priority.
UPDATE "EventTask" SET "isCritical" = true WHERE priority::text = 'CRITICAL';
UPDATE "TaskTemplate" SET "isCritical" = true WHERE priority::text = 'CRITICAL';
CREATE TYPE "TaskPriority_new" AS ENUM ('LOW', 'MEDIUM', 'HIGH');
ALTER TABLE "EventTask" ALTER COLUMN priority DROP DEFAULT;
ALTER TABLE "TaskTemplate" ALTER COLUMN priority DROP DEFAULT;
ALTER TABLE "EventTask" ALTER COLUMN priority TYPE "TaskPriority_new" USING
  (CASE WHEN priority::text = 'CRITICAL' THEN 'HIGH' ELSE priority::text END)::"TaskPriority_new";
ALTER TABLE "TaskTemplate" ALTER COLUMN priority TYPE "TaskPriority_new" USING
  (CASE WHEN priority::text = 'CRITICAL' THEN 'HIGH' ELSE priority::text END)::"TaskPriority_new";
DROP TYPE "TaskPriority";
ALTER TYPE "TaskPriority_new" RENAME TO "TaskPriority";
ALTER TABLE "EventTask" ALTER COLUMN priority SET DEFAULT 'MEDIUM';
ALTER TABLE "TaskTemplate" ALTER COLUMN priority SET DEFAULT 'MEDIUM';

COMMIT;
